"""C02: custody readback is not media execution permission.

Real SessionDB + neutral generated bytes + the gateway RPC handler. No provider
calls, live profile state or media-route enablement. The current route remains
text-only: readback must retain the input, report acceptance and refuse retry.
"""
from dataclasses import asdict

import pytest

from tests.tui_gateway.test_desktop_input_origin import desktop, send  # noqa: F401
from tests.ares_runtime.test_context_media_custody import png
from tui_gateway import server


def media_receipt(db, session):
    # Observe the existing transport/owner through the existing gateway owner.
    seed = send(session, event='seed', text='neutral seed')
    origin = db.read_context_input_origin('owned', seed)
    receipt = db.accept_context_media_input('owned', source='desktop', event_id='media',
        text='Inspect the neutral image',
        media=[{'data': png(), 'mime_type': 'image/png', 'display_name': 'neutral.png'}],
        desktop_origin=origin)
    return receipt


def read_status(text='Inspect the neutral image'):
    return server._methods['prompt.input_status']('readback', {
        'session_id': 'runtime', 'input_event_id': 'media', 'text': text})


def test_custodied_media_readback_reports_acceptance_without_granting_retry(desktop):
    db, session, _, _ = desktop
    receipt = media_receipt(db, session)
    frozen = asdict(receipt)
    original_origin = db.read_context_input_origin('owned', receipt)
    original_bytes = db.read_context_input_media('owned', receipt)
    result = read_status()
    assert 'error' not in result, result
    status = result['result']
    assert status['durable_input_accepted'] is True
    assert status['can_manual_retry'] is False
    assert status['execution_started'] is None
    assert status['payload_digest'] == receipt.payload_digest
    assert status['recovery_block_reason'] == 'CONTEXT_INPUT_TEXT_ROUTE_REQUIRED'
    assert asdict(db.read_context_input('owned', source='desktop', event_id='media')) == frozen
    assert db.read_context_input_origin('owned', receipt) == original_origin
    assert db.read_context_input_media('owned', receipt) == original_bytes == (png(),)
    assert db.get_messages('owned') == []


@pytest.mark.parametrize('flag', [
    'running', '_turn_cancel_requested', '_stop_pending', '_stop_uncertain',
    '_host_delivery_uncertain', '_compute_host_active_request_id',
])
def test_stop_busy_or_uncertain_media_never_becomes_manual_execution(desktop, flag):
    db, session, _, _ = desktop
    receipt = media_receipt(db, session)
    session[flag] = True
    response = read_status()
    assert 'error' not in response, response
    assert response['result']['durable_input_accepted'] is True
    assert response['result']['can_manual_retry'] is False
    assert db.read_context_input_media('owned', receipt) == (png(),)
    assert db.get_messages('owned') == []


def test_edited_media_text_conflicts_without_replacing_original(desktop):
    db, session, _, _ = desktop
    receipt = media_receipt(db, session)
    response = read_status('changed intent')
    assert 'error' in response
    assert 'CONTEXT_INPUT_ID_CONFLICT' in str(response['error'])
    assert db.read_context_input('owned', source='desktop', event_id='media') == receipt
    assert db.read_context_input_media('owned', receipt) == (png(),)


def test_manual_media_acceptance_remains_refused_and_receipt_is_retained(desktop):
    db, session, _, _ = desktop
    receipt = media_receipt(db, session)
    with pytest.raises(Exception, match='CONTEXT_INPUT_TEXT_ROUTE_REQUIRED'):
        server._accept_tui_context_input(session, receipt.content,
            event_id=receipt.event_id, manual_recovery=True)
    assert db.read_context_input('owned', source='desktop', event_id='media') == receipt
    assert db.read_context_input_media('owned', receipt) == (png(),)
    assert db.get_messages('owned') == []
